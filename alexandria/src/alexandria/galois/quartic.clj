(ns alexandria.galois.quartic
  "Galois (1831, printed 1846): the group of x^4 - 2 acting on its roots, as
   a special case of alexandria.structure.group (S_4 from
   alexandria.structure.groups/symmetric).

     roots      r_k = 2^(1/4) i^k, k = 0..3: the points [a 0] [0 a] [-a 0]
                [0 -a], a = 2^(1/4), numbers from a raster kernel.
     relations  r_0 + r_2 = 0 and r_1 + r_3 = 0, rational relations among
                the roots. Galois' Proposition I: the group of the equation
                is the set of permutations that keep every such relation.
     group      the permutations of S_4 keeping both relations: the
                dihedral group D_4 of the square, 8 elements, generated by
                sigma (multiply by i: r_k -> r_(k+1)) and tau (complex
                conjugation: r_k -> r_(-k)).
     table      the 24 permutations of S_4, each with its cycles, whether it
                keeps the relations, and the residuals that decide it.

   Permutations are vectors s with (s k) the image of root k, as in
   alexandria.structure.groups/symmetric."
  (:require [alexandria.raster :as raster]
            [alexandria.structure.group :as g]
            [alexandria.structure.groups :as groups]
            [emmy.env :as e]
            [hive-dsl.result :as r]))

(def S4 "The symmetric group on the four roots." (groups/symmetric 4))

(def sigma "Multiplication by i: r_k -> r_(k+1)." [1 2 3 0])
(def tau "Complex conjugation: r_k -> r_(-k)." [0 3 2 1])

(defn root
  "[re im] of r_k = 2^(1/4) i^k as an Emmy expression in k."
  [k]
  (let [a (e/expt 2 (e// 1 4)) t (e/* k (e// Math/PI 2))]
    [(e/* a (e/cos t)) (e/* a (e/sin t))]))

(defn roots
  "The four roots as [[re im] ...], each number from a raster kernel."
  []
  (mapv (fn [[x y]] [(if (< (Math/abs (double x)) 1e-12) 0.0 x) (if (< (Math/abs (double y)) 1e-12) 0.0 y)])
        (raster/sample (fn [k] (root k)) [[0] [1] [2] [3]])))

(defn quartic-residuals
  "|r_k^4 - 2| for the four roots, on raster: (a e^(i t))^4 = a^4 e^(4 i t)."
  []
  (raster/sample (fn [k] (let [[x y] (root k)
                               re2 (e/- (e/square x) (e/square y)) im2 (e/* 2 x y)]
                           (e/- (e/- (e/square re2) (e/square im2)) 2)))
                 [[0] [1] [2] [3]]))

(def relations
  "The rational relations among the roots used here: pairs [i j] with
   r_i + r_j = 0."
  [[0 2] [1 3]])

(defn residuals
  "For permutation s: |r_s(i) + r_s(j)| for each relation [i j]. A
   permutation of the group gives 0 on every one."
  [rts s]
  (mapv (fn [[i j]] (let [[x1 y1] (rts (s i)) [x2 y2] (rts (s j))]
                      (Math/hypot (+ x1 x2) (+ y1 y2))))
        relations))

(defn keeps? [rts s] (every? #(< % 1e-9) (residuals rts s)))

(defn cycles
  "Cycle notation of s on the roots 0..3, e.g. \"(0 1 2 3)\", \"e\" for the identity."
  [s]
  (let [cs (loop [seen #{} out [] ks (range (count s))]
             (if-let [k (first (remove seen ks))]
               (let [c (loop [c [k] x (s k)] (if (= x k) c (recur (conj c x) (s x))))]
                 (recur (into seen c) (if (> (count c) 1) (conj out c) out) ks))
               out))]
    (if (empty? cs) "e" (apply str (map #(str "(" (clojure.string/join " " %) ")") cs)))))

(defn all-perms
  "The 24 elements of S_4 (closure of a 4-cycle and a transposition)."
  []
  (sort (:ok (g/closure S4 [[1 2 3 0] [1 0 2 3]]))))

(defn galois-group
  "The group of x^4 - 2 as the closure of sigma and tau in S_4 (Ok [s ...])."
  []
  (g/closure S4 [sigma tau]))

(defn table
  "[{:perm s :cycles str :keeps? bool :residuals [..]}] over S_4."
  []
  (let [rts (roots)]
    (mapv (fn [s] {:perm s :cycles (cycles s) :keeps? (keeps? rts s) :residuals (residuals rts s)})
          (all-perms))))
