(ns alexandria.galois.solvable
  "Galois' criterion, the letter to Chevalier (29 May 1832): the group of
   an equation must be lowered by proper decompositions (normal subgroups)
   with quotients of prime order. Special cases of
   alexandria.structure.group on S_4 and S_5 (alexandria.structure.groups).

     S_4 > A_4 > V_4 > Z_2 > 1   orders 24, 12, 4, 2, 1; indices 2, 3, 2, 2
     S_5 > A_5 > 1               A_5 (order 60 = 5.4.3) has no proper normal
                                 subgroup, so the chain stops: not solvable.

   normal?           H is normal in G: g h g^-1 in H for all g, h
   chain-report      per step: orders, index, normal?, quotient abelian
                     (every commutator of G lands in H)
   derived           the derived subgroup [G, G] (closure of commutators)
   derived-series    G, G', G'', ... until it stops
   graded            the claims, graded (exact counts are :grade/proved by
                     Emmy on the differences; the root check is raster)"
  (:require [alexandria.grade :as grade]
            [alexandria.raster :as raster]
            [alexandria.structure.group :as g]
            [alexandria.structure.groups :as groups]
            [emmy.env :as e]
            [hive-dsl.result :as r]))

(defn- gen [G gens] (vec (sort (:ok (g/closure G gens 200)))))

(defn S [n] (groups/symmetric n))

(defn sign
  "+1 or -1: the parity of the permutation s (by counting inversions)."
  [s]
  (if (even? (count (for [i (range (count s)) j (range (inc i) (count s)) :when (> (s i) (s j))] 1))) 1 -1))

(defn elements [n] (gen (S n) [(vec (concat (range 1 n) [0])) (vec (concat [1 0] (range 2 n)))]))

(defn alternating [n] (filterv #(= 1 (sign %)) (elements n)))

(defn derived
  "[G, G]: the subgroup generated by every commutator of elems in S_n."
  [n elems]
  (let [G (S n) cs (distinct (for [a elems b elems] (g/commutator G a b)))]
    (gen G cs)))

(defn derived-series
  "Orders along G, G', G'', ... until the subgroup repeats."
  [n elems]
  (loop [cur elems out [(count elems)]]
    (let [nxt (derived n cur)]
      (if (= (count nxt) (count cur)) out (recur nxt (conj out (count nxt)))))))

(defn normal?
  "H normal in G (elements of S_n): every conjugate g h g^-1 is in H."
  [n G H]
  (let [Hs (set H)] (every? Hs (for [a G h H] (g/conjugate (S n) a h)))))

(defn abelian-quotient?
  "G/H abelian: every commutator of G lies in H."
  [n G H]
  (let [Hs (set H)] (every? Hs (for [a G b G] (g/commutator (S n) a b)))))

(defn chain-S4
  "The composition series S_4 > A_4 > V_4 > Z_2 > 1, as element lists."
  []
  (let [s4 (elements 4) a4 (alternating 4)
        v4 (gen (S 4) [[1 0 3 2] [2 3 0 1]])
        z2 (gen (S 4) [[1 0 3 2]])]
    [s4 a4 v4 z2 [[0 1 2 3]]]))

(defn chain-S5 [] [(elements 5) (alternating 5) [[0 1 2 3 4]]])

(defn chain-report
  "[{:orders [|G| |H|] :index :normal? :abelian?}] along a chain in S_n."
  [n chain]
  (mapv (fn [[G H]] {:orders [(count G) (count H)] :index (quot (count G) (count H))
                     :normal? (normal? n G H) :abelian? (abelian-quotient? n G H)})
        (partition 2 1 chain)))

(defn normal-subgroups-A5
  "Orders of the normal subgroups of A_5 that are unions of conjugacy
   classes containing 1 and whose size divides 60: class sizes 1, 15, 20,
   12, 12 admit only 1 and 60."
  []
  (let [a5 (alternating 5) G (S 5)
        classes (vals (group-by (fn [h] (set (for [a a5] (g/conjugate G a h)))) a5))
        sizes (sort (map count classes))
        sums (set (for [mask (range 16) :let [pick (keep-indexed #(when (bit-test mask %1) %2) (rest sizes))]]
                    (reduce + 1 pick)))]
    {:class-sizes sizes :admissible (sort (filter #(zero? (mod 60 %)) sums))}))

(defn graded
  "[{:label :grade}] of the Galois shelf: counts as exact Emmy differences
   (:grade/proved), the roots of x^4 - 2 on raster (:grade/numeric)."
  []
  (let [variant (fn [kind diffs tol] (let [res (grade/grade kind diffs tol)]
                                       (if (r/ok? res) (get-in res [:ok :adt/variant]) :grade/fails)))
        s4 (chain-report 4 (chain-S4)) s5 (chain-report 5 (chain-S5))
        a5 (normal-subgroups-A5)
        res4 ((requiring-resolve 'alexandria.galois.quartic/quartic-residuals))
        d4 (count (:ok ((requiring-resolve 'alexandria.galois.quartic/galois-group))))
        ok? (fn [rep k] (if (every? k rep) 0 1))]
    [{:label "the roots 2^(1/4) i^k satisfy x⁴ = 2 (raster, four roots)"
      :grade (variant :numeric res4 1e-12)}
     {:label "the group of x⁴ − 2 (closure of σ and τ in S₄) has 8 = 24 / 3 elements"
      :grade (variant :symbolic [(e/- d4 8) (e/- 24 (e/* 3 d4))] grade/default-tolerance)}
     {:label "S₄ > A₄ > V₄ > Z₂ > 1: indices 2, 3, 2, 2, all prime, their product 24"
      :grade (variant :symbolic [(e/- (reduce e/* (map :index s4)) 24) (e/- (count (filter #{2 3} (map :index s4))) 4)]
                      grade/default-tolerance)}
     {:label "each step of the S₄ chain is normal with an abelian quotient (all pairs checked)"
      :grade (variant :symbolic [(ok? s4 :normal?) (ok? s4 :abelian?)] grade/default-tolerance)}
     {:label "S₅ > A₅ is normal of index 2, and A₅ over 1 is not abelian: index 60 = 5·4·3, Galois' number"
      :grade (variant :symbolic [(ok? s5 :normal?) (e/- (:index (second s5)) (e/* 5 4 3))
                                 (if (:abelian? (second s5)) 1 0)]
                      grade/default-tolerance)}
     {:label "the classes of A₅ have sizes 1, 12, 12, 15, 20: only 1 and 60 are unions containing 1 that divide 60"
      :grade (variant :symbolic [(e/- (reduce + (:class-sizes a5)) 60) (e/- (count (:admissible a5)) 2)]
                      grade/default-tolerance)}
     {:label "derived series: S₄, A₄, V₄, 1 reach the identity; S₅, A₅ stop at A₅"
      :grade (variant :symbolic [(e/- (last (derived-series 4 (elements 4))) 1)
                                 (e/- (last (derived-series 5 (elements 5))) 60)]
                      grade/default-tolerance)}]))
