(ns alexandria.structure.group
  "Domain stratum: a group, and a group acting on a set.

   Group   (unit G) (compose G a b) = a after b, (inverse G a), and
           (same? G a b), equality of elements (exact for exact elements,
           within a tolerance for numbers).
   Action  (act A g x): the image of the point x under g.

   Laws (the conformance suite test/alexandria/structure/group_contract.clj
   checks them for every instance on generated elements and points):
     associativity  (compose (compose a b) c) = (compose a (compose b c))
     unit           (compose e a) = a = (compose a e)
     inverse        (compose a (inverse a)) = e
     action         (act e x) = x, (act (compose a b) x) = (act a (act b x))

   Derived here, for every instance: power, conjugate, commutator, word
   (a product of generators named by keys), closure (the finite group
   generated), orbit and stabilizer-of on a finite point set.

   Elements and points are Emmy values, so one definition gives TeX on
   symbols, exact grades and raster kernels. Instances live in
   alexandria.structure.groups."
  (:require [hive-dsl.result :as r]))

(defprotocol Group
  (unit [G] "The identity element.")
  (compose [G a b] "a after b.")
  (inverse [G a] "The element undoing a.")
  (same? [G a b] "True when a and b are the same element of G."))

(defprotocol Action
  (act [A g x] "The image of point x under the element g."))

;; ---------------------------------------------------------------------------
;; Derived operations

(defn power
  "g composed with itself n times (n an integer; negative n uses the
   inverse, 0 the unit)."
  [G g n]
  (let [base (if (neg? n) (inverse G g) g)]
    (loop [k (Math/abs (long n)) acc (unit G)]
      (if (zero? k) acc (recur (dec k) (compose G base acc))))))

(defn conjugate "g h g^-1." [G g h] (compose G g (compose G h (inverse G g))))

(defn commutator "g h g^-1 h^-1." [G g h]
  (compose G (compose G g h) (compose G (inverse G g) (inverse G h))))

(defn word
  "The product of the generators named in ks (left to right: the first
   applied last), gens a map key -> element."
  [G gens ks]
  (reduce (fn [acc k] (compose G acc (gens k))) (unit G) ks))

(defn closure
  "The finite group generated by gens (a seq of elements), as a Result:
   Ok [element ...] in breadth-first order from the unit, or Err
   {:alexandria/error :group/too-large} past max elements (default 512)."
  ([G gens] (closure G gens 512))
  ([G gens max]
   (loop [elems [(unit G)] frontier [(unit G)]]
     (cond
       (> (count elems) max)
       (r/err {:alexandria/error :group/too-large :max max})

       (empty? frontier) (r/ok elems)

       :else
       (let [[elems' new]
             (reduce (fn [[es nw] x]
                       (reduce (fn [[es nw] g]
                                 (let [y (compose G g x)]
                                   (if (some #(same? G % y) es) [es nw] [(conj es y) (conj nw y)])))
                               [es nw] gens))
                     [elems []] frontier)]
         (recur elems' new))))))

(defn order
  "The least n >= 1 with g^n = e, as a Result (Err past max, default 512)."
  ([G g] (order G g 512))
  ([G g max]
   (loop [n 1 x g]
     (cond (same? G x (unit G)) (r/ok n)
           (>= n max) (r/err {:alexandria/error :group/infinite-order :max max})
           :else (recur (inc n) (compose G g x))))))

(defn orbit
  "The orbit of x under the elements elems (a finite group listed), with
   same-point? deciding equality of points: distinct points, in order."
  [A elems x same-point?]
  (reduce (fn [acc g] (let [y (act A g x)] (if (some #(same-point? % y) acc) acc (conj acc y))))
          [] elems))

(defn stabilizer
  "The elements of elems fixing x."
  [A elems x same-point?]
  (filterv #(same-point? (act A % x) x) elems))
